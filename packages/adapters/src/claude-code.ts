import { guardrailsMarkdown, writeFrontmatter, type Agent, type Project, type TeamState } from '@teamops/core';

export interface GeneratedFile { path: string; content: string }

const HEADER = '<!-- Generated by TeamOps. Edit in TeamOps, not here: this file is overwritten on every export. -->';

export function agentFile(agent: Agent): GeneratedFile {
  const body = [agent.prompt.trim() || `Você é ${agent.name}. ${agent.title}`.trim(), guardrailsMarkdown(agent.guardrails)].filter(Boolean).join('\n\n');
  const meta: Record<string, string | undefined> = {
    name: agent.slug,
    description: agent.description || agent.title,
    tools: agent.tools.length ? agent.tools.join(', ') : undefined,
    model: agent.model && agent.model !== 'inherit' ? agent.model : undefined,
  };
  return { path: `.claude/agents/${agent.slug}.md`, content: writeFrontmatter(meta, `${HEADER}\n\n${body}`) };
}

/** Everything the Claude Code engine reads for one project. Secrets never leave the instance: env values become ${VAR}. */
export function generateClaudeCode(state: TeamState, project: Project): GeneratedFile[] {
  const agents = state.agents.filter((a) => a.projectIds.includes(project.id) && a.status === 'active' && a.engine === 'claude-code');
  const files = agents.map(agentFile);

  const rules = state.rules.filter((r) => r.active && (r.projectId === null || r.projectId === project.id)).sort((a, b) => a.position - b.position);
  const groups = new Map(state.groups.map((g) => [g.id, g.name]));
  const md: string[] = [HEADER, '', `# ${project.name}`, ''];
  if (project.description) md.push(project.description, '');
  if (state.corp.name) md.push(`Time: **${state.corp.name}**${state.corp.tagline ? ` · ${state.corp.tagline}` : ''}`, '');
  if (agents.length) {
    md.push('## Agentes', '', '| Agente | Grupo | Modelo | Quando usar |', '|---|---|---|---|');
    for (const a of agents) md.push(`| **${a.name}** (\`${a.slug}\`) | ${a.groupId ? groups.get(a.groupId) ?? '-' : '-'} | ${a.model} | ${(a.description || a.title).replace(/\|/g, '/').replace(/\n/g, ' ')} |`);
    md.push('');
  }
  let cat = '';
  for (const r of rules) {
    if (r.category !== cat) { cat = r.category; md.push(`## ${cat || 'Regras gerais'}`, ''); }
    md.push(`### ${r.title}`, '', r.body.trim(), '');
  }
  files.push({ path: 'CLAUDE.md', content: md.join('\n').replace(/\n{3,}/g, '\n\n').trim() + '\n' });

  const used = new Set(agents.flatMap((a) => a.tools));
  const servers: Record<string, unknown> = {};
  for (const m of state.mcps) {
    if (!m.enabled) continue;
    if (!state.tools.some((t) => t.mcpId === m.id && used.has(t.key))) continue;
    const env = Object.fromEntries(Object.keys(m.env).map((k) => [k, `\${${k}}`]));
    servers[m.name] = m.transport === 'stdio'
      ? { command: m.command, args: m.args, ...(Object.keys(env).length ? { env } : {}) }
      : { type: m.transport, url: m.url };
  }
  files.push({ path: '.mcp.json', content: JSON.stringify({ mcpServers: servers }, null, 2) + '\n' });
  return files;
}
